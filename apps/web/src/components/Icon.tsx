/** Round initials badge used for farmers and staff. */
export function Avatar({ name, className = "h-10 w-10 text-sm" }: { name: string; className?: string }) {
  const initials = name
    .split(" ")
    .filter(Boolean)
    .map((p) => p[0])
    .slice(0, 2)
    .join("")
    .toUpperCase();
  return (
    <div
      className={`flex shrink-0 items-center justify-center rounded-full bg-coffee-100 font-semibold text-coffee-700 ${className}`}
    >
      {initials || "?"}
    </div>
  );
}
